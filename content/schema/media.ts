import { z } from "zod";
import { aspect, mediaId, review, slug } from "./common";

const base = { id: slug, ...review };

/**
 * Still image. `file` is where it lives under public/media. `pnpm media:sync` creates it from
 * `origin` (a URL) or `local` (a path inside this repo) and records its size and blur placeholder
 * in media.manifest.json. Alt text is mandatory unless the image is purely decorative.
 */
export const imageMedia = z
  .object({
    kind: z.literal("image"),
    ...base,
    file: z.string().regex(/^[a-z0-9-]+\.(jpg|png|webp)$/, "file must be lowercase-kebab.jpg|png|webp"),
    origin: z.url().optional(),
    local: z.string().optional(),
    maxWidth: z.number().int().positive().optional(),
    credit: z.string().optional(),
    alt: z.string(),
    decorative: z.boolean().optional(),
  })
  .refine((m) => Boolean(m.origin) !== Boolean(m.local), {
    message: "set exactly one of `origin` or `local`",
    path: ["origin"],
  })
  .refine((m) => m.decorative === true || m.alt.trim().length >= 3, {
    message: "alt text is required (min 3 characters) unless decorative: true",
    path: ["alt"],
  });

/** A video file streamed from its own URL, with an optional short silent preview clip for hover. */
export const videoMedia = z.object({
  kind: z.literal("video"),
  ...base,
  src: z.url(),
  poster: mediaId,
  /** File name under public/media/previews, produced by `pnpm media:sync` with ffmpeg. */
  preview: z.string().regex(/^[a-z0-9-]+\.mp4$/).optional(),
  previewStartSec: z.number().nonnegative().optional(),
  /** Height in pixels of the preview clip. Default 360; use 720 for large frames. */
  previewHeight: z.number().int().min(240).max(1080).optional(),
  aspect,
  title: z.string().min(1),
  durationSec: z.number().positive().optional(),
});

export const youtubeMedia = z.object({
  kind: z.literal("youtube"),
  ...base,
  videoId: z.string().length(11),
  title: z.string().min(1),
  thumbnail: mediaId,
  aspect,
});

export const mediaItem = z.discriminatedUnion("kind", [imageMedia, videoMedia, youtubeMedia]);
export type MediaItem = z.infer<typeof mediaItem>;
export type ImageMedia = z.infer<typeof imageMedia>;
export type VideoMedia = z.infer<typeof videoMedia>;
export type YoutubeMedia = z.infer<typeof youtubeMedia>;

export const mediaList = z.array(mediaItem);

/** Generated by `pnpm media:sync`. Never edited by hand. */
export const mediaManifest = z.record(
  z.string(),
  z.object({
    width: z.number().int().positive(),
    height: z.number().int().positive(),
    blurDataURL: z.string(),
    bytes: z.number().int().positive(),
  }),
);
export type MediaManifest = z.infer<typeof mediaManifest>;
